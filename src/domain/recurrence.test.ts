import { describe, expect, it } from 'vitest'
import { expand, type Rule } from './recurrence'

const never: Rule['ends'] = { mode: 'never' }
const on = (d: string): Rule['ends'] => ({ mode: 'on', on: d })
const after = (n: number): Rule['ends'] => ({ mode: 'after', after: n })

function daily(starts_on: string, step: number, ends: Rule['ends'] = never): Rule {
  return { freq: 'daily', step, starts_on, ends }
}
function weekly(starts_on: string, step: number, byweekday?: number[], ends: Rule['ends'] = never): Rule {
  return byweekday === undefined
    ? { freq: 'weekly', step, starts_on, ends }
    : { freq: 'weekly', step, byweekday, starts_on, ends }
}
function monthly(starts_on: string, step: number, bymonthday?: number, ends: Rule['ends'] = never): Rule {
  return bymonthday === undefined
    ? { freq: 'monthly', step, starts_on, ends }
    : { freq: 'monthly', step, bymonthday, starts_on, ends }
}
function yearly(starts_on: string, step: number, ends: Rule['ends'] = never): Rule {
  return { freq: 'yearly', step, starts_on, ends }
}

describe('expand: общие границы окна', () => {
  it('from > to даёт пустой список', () => {
    expect(expand(daily('2025-03-10', 1), '2025-03-15', '2025-03-14')).toEqual([])
  })

  it('окно целиком до starts_on даёт пустой список', () => {
    expect(expand(daily('2025-03-10', 1), '2025-02-01', '2025-02-10')).toEqual([])
  })

  it('окно из одного дня, совпадающего с повторением, возвращает его', () => {
    expect(expand(daily('2025-03-10', 1), '2025-03-10', '2025-03-10')).toEqual(['2025-03-10'])
  })
})

describe('daily', () => {
  it('step=1, окно внутри серии', () => {
    expect(expand(daily('2025-03-10', 1), '2025-03-12', '2025-03-15'))
      .toEqual(['2025-03-12', '2025-03-13', '2025-03-14', '2025-03-15'])
  })

  it('step=3, окно внутри серии попадает только на кратные шагу дни', () => {
    // серия: 10, 13, 16, 19, 22, 25 марта
    expect(expand(daily('2025-03-10', 3), '2025-03-14', '2025-03-23'))
      .toEqual(['2025-03-16', '2025-03-19', '2025-03-22'])
  })

  it('окно частично до starts_on: даты раньше starts_on не возвращаются', () => {
    expect(expand(daily('2025-03-10', 3), '2025-03-05', '2025-03-14'))
      .toEqual(['2025-03-10', '2025-03-13'])
  })

  it('step=99 не зацикливается и прыгает сразу к окну', () => {
    // 2025-01-01 + 99 дней = 2025-04-10; следующее (2025-07-18) вне окна
    expect(expand(daily('2025-01-01', 99), '2025-01-01', '2025-07-01'))
      .toEqual(['2025-01-01', '2025-04-10'])
  })
})

describe('weekly', () => {
  // 2025-03-03 — понедельник
  it('вт и пт каждую неделю: byweekday не отсортирован и с дублем — результат по возрастанию без дублей', () => {
    expect(expand(weekly('2025-03-03', 1, [5, 2, 5]), '2025-03-03', '2025-03-21'))
      .toEqual(['2025-03-04', '2025-03-07', '2025-03-11', '2025-03-14', '2025-03-18', '2025-03-21'])
  })

  it('окно позже starts_on: пятница за верхней границей отрезается', () => {
    expect(expand(weekly('2025-03-03', 1, [2, 5]), '2025-03-17', '2025-03-19'))
      .toEqual(['2025-03-18'])
  })

  it('окно начинается посреди недели: вторник до from не возвращается', () => {
    expect(expand(weekly('2025-03-03', 1, [2, 5]), '2025-03-05', '2025-03-07'))
      .toEqual(['2025-03-07'])
  })

  it('step=2, несколько дней: недели чередуются от недели starts_on', () => {
    // неделя 0: пн 03-03, чт 03-06; неделя 2: пн 03-17, чт 03-20
    expect(expand(weekly('2025-03-03', 2, [1, 4]), '2025-03-03', '2025-03-23'))
      .toEqual(['2025-03-03', '2025-03-06', '2025-03-17', '2025-03-20'])
  })

  it('step=2: промежуточная неделя пуста', () => {
    expect(expand(weekly('2025-03-03', 2, [1, 4]), '2025-03-10', '2025-03-16')).toEqual([])
  })

  it('starts_on в среду: понедельник той же недели не возвращается и не тратит счётчик after', () => {
    // 2025-03-05 — среда; пн 03-03 до starts_on; повторения: ср 03-05, пн 03-10, ср 03-12
    expect(expand(weekly('2025-03-05', 1, [1, 3], after(3)), '2025-03-01', '2025-03-31'))
      .toEqual(['2025-03-05', '2025-03-10', '2025-03-12'])
  })

  it('after считается от начала серии, а не от окна', () => {
    // повторения: 03-04, 03-07, 03-11, 03-14 — первые два до окна съедают счётчик
    expect(expand(weekly('2025-03-03', 1, [2, 5], after(4)), '2025-03-10', '2025-03-31'))
      .toEqual(['2025-03-11', '2025-03-14'])
  })

  it('без byweekday берётся день недели starts_on', () => {
    expect(expand(weekly('2025-03-05', 1), '2025-03-01', '2025-03-19'))
      .toEqual(['2025-03-05', '2025-03-12', '2025-03-19'])
  })

  it('пустой byweekday равносилен отсутствию', () => {
    expect(expand(weekly('2025-03-05', 2, []), '2025-03-01', '2025-03-31'))
      .toEqual(['2025-03-05', '2025-03-19'])
  })

  it('переход через год: серия с конца декабря продолжается в январе', () => {
    // 2025-12-22 — понедельник; ср и сб
    expect(expand(weekly('2025-12-22', 1, [3, 6]), '2025-12-22', '2026-01-07'))
      .toEqual(['2025-12-24', '2025-12-27', '2025-12-31', '2026-01-03', '2026-01-07'])
  })

  it('step=99 не зацикливается', () => {
    // 2025-01-06 (пн) + 99 недель = 2026-11-30
    expect(expand(weekly('2025-01-06', 99, [1]), '2025-01-01', '2027-12-31'))
      .toEqual(['2025-01-06', '2026-11-30'])
  })
})

describe('monthly', () => {
  it('bymonthday=31: февраль пропущен, не сдвигаясь на 28-е', () => {
    expect(expand(monthly('2025-01-15', 1, 31), '2025-01-01', '2025-04-30'))
      .toEqual(['2025-01-31', '2025-03-31'])
  })

  it('bymonthday=31: месяцы с 30 днями тоже пропущены', () => {
    expect(expand(monthly('2025-01-15', 1, 31), '2025-01-01', '2025-07-31'))
      .toEqual(['2025-01-31', '2025-03-31', '2025-05-31', '2025-07-31'])
  })

  it('step=2 от 31 января: каждый второй месяц от месяца starts_on', () => {
    const got = expand(monthly('2025-01-31', 2), '2025-01-01', '2025-07-31')
    expect(got).toEqual(['2025-01-31', '2025-03-31', '2025-05-31', '2025-07-31'])
    expect(got).not.toContain('2025-02-28')
    expect(got).not.toContain('2025-04-30')
  })

  it('step=4 от 31 января: 31 мар вне шага, сентябрь (30 дней) пропущен', () => {
    const got = expand(monthly('2025-01-31', 4), '2025-01-01', '2026-01-31')
    expect(got).toEqual(['2025-01-31', '2025-05-31', '2026-01-31'])
    expect(got).not.toContain('2025-03-31')
  })

  it('bymonthday раньше числа starts_on: дата первого месяца не возвращается', () => {
    expect(expand(monthly('2025-01-20', 1, 10), '2025-01-01', '2025-03-31'))
      .toEqual(['2025-02-10', '2025-03-10'])
  })

  it('пропущенная дата до starts_on не тратит счётчик after', () => {
    // 10 янв < starts_on; серия из двух: 10 фев, 10 мар — 10 апр уже нет
    expect(expand(monthly('2025-01-20', 1, 10, after(2)), '2025-01-01', '2025-12-31'))
      .toEqual(['2025-02-10', '2025-03-10'])
  })

  it('окно позже starts_on: прыжок к окну не теряет и не добавляет месяцев', () => {
    expect(expand(monthly('2025-01-31', 2), '2025-04-01', '2025-08-31'))
      .toEqual(['2025-05-31', '2025-07-31'])
  })

  it('верхняя граница посреди месяца отрезает его повторение', () => {
    expect(expand(monthly('2025-01-15', 1), '2025-01-01', '2025-03-10'))
      .toEqual(['2025-01-15', '2025-02-15'])
  })
})

describe('yearly', () => {
  it('от 2024-02-29: невисокосные 2025–2027 пропущены, 2028 есть', () => {
    expect(expand(yearly('2024-02-29', 1), '2024-01-01', '2028-12-31'))
      .toEqual(['2024-02-29', '2028-02-29'])
  })

  it('окно позже starts_on: прыжок к окну работает вместе с пропуском лет', () => {
    expect(expand(yearly('2024-02-29', 1), '2027-01-01', '2028-12-31'))
      .toEqual(['2028-02-29'])
  })

  it('step=2 от 2024-02-29: 2026 невисокосный и пропущен, дата до from отфильтрована', () => {
    expect(expand(yearly('2024-02-29', 2), '2024-06-01', '2028-12-31'))
      .toEqual(['2028-02-29'])
  })

  it('after ограничивает серию независимо от ширины окна', () => {
    expect(expand(yearly('2025-07-04', 1, after(2)), '2025-01-01', '2030-12-31'))
      .toEqual(['2025-07-04', '2026-07-04'])
  })

  it('верхняя граница посреди года отрезает его повторение', () => {
    expect(expand(yearly('2025-07-04', 1), '2025-01-01', '2026-05-01'))
      .toEqual(['2025-07-04'])
  })
})

describe('ends.on', () => {
  it('граница включительно: повторение ровно на ends.on возвращается, следующее — нет', () => {
    // серия: 04-01, 04-03, 04-05, 04-07, (04-09 уже за ends.on)
    expect(expand(daily('2025-04-01', 2, on('2025-04-07')), '2025-04-01', '2025-04-30'))
      .toEqual(['2025-04-01', '2025-04-03', '2025-04-05', '2025-04-07'])
  })

  it('ends.on за пределами окна не сужает его', () => {
    expect(expand(daily('2025-04-01', 1, on('2025-04-10')), '2025-04-05', '2025-04-07'))
      .toEqual(['2025-04-05', '2025-04-06', '2025-04-07'])
  })

  it('ends.on раньше окна даёт пустой список', () => {
    expect(expand(daily('2025-04-01', 1, on('2025-04-03')), '2025-04-05', '2025-04-10')).toEqual([])
  })
})

describe('ends.after', () => {
  it('серия из 5 обрывается ровно на границе: шестой даты нет', () => {
    expect(expand(daily('2025-05-01', 1, after(5)), '2025-05-01', '2025-05-10'))
      .toEqual(['2025-05-01', '2025-05-02', '2025-05-03', '2025-05-04', '2025-05-05'])
  })

  it('окно позже конца серии даёт пустой список', () => {
    expect(expand(daily('2025-05-01', 1, after(5)), '2025-05-06', '2025-05-31')).toEqual([])
  })

  it('окно захватывает хвост серии', () => {
    expect(expand(daily('2025-05-01', 1, after(5)), '2025-05-04', '2025-05-08'))
      .toEqual(['2025-05-04', '2025-05-05'])
  })

  it('after=0 даёт пустой список', () => {
    expect(expand(daily('2025-05-01', 1, after(0)), '2025-05-01', '2025-05-31')).toEqual([])
  })
})
